/**
 * Switch the active locale at runtime.
 * Persists the selection to localStorage for subsequent visits.
 */
export function switchLocale(locale: string): void {
  if (locale in messages) {
    (i18n.global.locale.value as string) = locale;
    localStorage.setItem('language', locale);
  }
}

export default i18n;
